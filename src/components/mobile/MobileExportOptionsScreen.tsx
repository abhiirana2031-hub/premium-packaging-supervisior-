'use client';

import React, { useState } from 'react';
import {
  ArrowLeft,
  Calendar,
  FileText,
  FileSpreadsheet,
  FileCode,
  Printer,
  Share2,
  CheckCircle,
} from 'lucide-react';
import { MobileStatusBar } from './MobileStatusBar';
import { ProductionRecord, UserProfile } from '@/types';
import { exportProductionPdf } from '@/lib/exportPdf';
import { exportProductionExcel } from '@/lib/exportExcel';
import { exportProductionCsv } from '@/lib/exportCsv';

interface MobileExportOptionsScreenProps {
  records: ProductionRecord[];
  currentUser: UserProfile;
  companyName: string;
  reportTitle?: string;
  dateRangeDisplay?: string;
  onBack: () => void;
}

export function MobileExportOptionsScreen({
  records,
  currentUser,
  companyName,
  reportTitle = 'Daily Production Report',
  dateRangeDisplay = 'Current Period',
  onBack,
}: MobileExportOptionsScreenProps) {
  const [successToast, setSuccessToast] = useState<string | null>(null);

  const showToast = (msg: string) => {
    setSuccessToast(msg);
    setTimeout(() => setSuccessToast(null), 3000);
  };

  const handlePdf = async () => {
    try {
      await exportProductionPdf({
        reportTitle,
        companyName,
        dateRangeDisplay,
        records,
        currentUser,
      });
      showToast('PDF downloaded successfully!');
    } catch (e) {
      console.error(e);
    }
  };

  const handleExcel = async () => {
    try {
      await exportProductionExcel({
        reportTitle,
        companyName,
        dateRangeDisplay,
        records,
        currentUser,
      });
      showToast('Excel spreadsheet downloaded!');
    } catch (e) {
      console.error(e);
    }
  };

  const handleCsv = () => {
    exportProductionCsv({
      reportTitle,
      records,
    });
    showToast('CSV file downloaded!');
  };

  const handlePrint = () => {
    window.print();
  };

  const handleShare = async () => {
    const text = `*${companyName} — ${reportTitle}*\nPeriod: ${dateRangeDisplay}\nTotal Records: ${records.length}\nGenerated By: ${currentUser.fullName}`;
    if (navigator.share) {
      try {
        await navigator.share({
          title: reportTitle,
          text,
        });
      } catch (err) {
        // Fallback to WhatsApp Web link
        window.open(`https://api.whatsapp.com/send?text=${encodeURIComponent(text)}`, '_blank');
      }
    } else {
      window.open(`https://api.whatsapp.com/send?text=${encodeURIComponent(text)}`, '_blank');
    }
    showToast('Share link triggered!');
  };

  return (
    <div className="flex flex-col h-full bg-slate-50 select-none relative">
      <MobileStatusBar />

      {/* Top App Bar */}
      <div className="flex items-center justify-between px-5 py-3 bg-white border-b border-slate-100">
        <button
          type="button"
          onClick={onBack}
          className="p-1.5 -ml-1 text-slate-700 hover:bg-slate-100 rounded-full transition-colors"
        >
          <ArrowLeft className="w-5 h-5" />
        </button>

        <h1 className="text-sm font-bold text-slate-900">Export Options</h1>

        <div className="w-5" />
      </div>

      {/* Success Toast */}
      {successToast && (
        <div className="absolute top-14 left-4 right-4 z-40 bg-emerald-600 text-white text-xs font-semibold px-4 py-2.5 rounded-xl shadow-lg flex items-center gap-2 animate-bounce">
          <CheckCircle className="w-4 h-4 stroke-[2.5]" />
          <span>{successToast}</span>
        </div>
      )}

      {/* Date & Report Chip */}
      <div className="p-4 bg-white border-b border-slate-100 space-y-2 text-left">
        <div className="flex items-center gap-1.5 text-xs font-semibold text-slate-700">
          <Calendar className="w-3.5 h-3.5 text-blue-600" />
          <span>{dateRangeDisplay}</span>
        </div>
        <div className="bg-slate-50 border border-slate-200/80 rounded-xl px-3 py-2 flex items-center justify-between">
          <span className="text-xs font-bold text-slate-800">{reportTitle}</span>
          <span className="text-[10px] font-bold text-blue-600 bg-blue-50 px-2 py-0.5 rounded-md">
            Ready
          </span>
        </div>
      </div>

      {/* Export Action Tiles */}
      <div className="flex-1 overflow-y-auto p-4 space-y-2.5 text-left">
        {/* PDF Tile */}
        <div
          onClick={handlePdf}
          className="bg-white rounded-2xl border border-slate-200/80 p-3.5 shadow-2xs flex items-center gap-3.5 hover:border-rose-400 transition-all cursor-pointer"
        >
          <div className="w-11 h-11 rounded-xl bg-rose-50 text-rose-600 border border-rose-200/70 flex items-center justify-center shrink-0">
            <FileText className="w-5 h-5 stroke-[2.2]" />
          </div>
          <div>
            <div className="text-xs font-bold text-slate-900">Download PDF</div>
            <div className="text-[10px] text-slate-500 font-medium mt-0.5">
              Best for printing and sharing official reports
            </div>
          </div>
        </div>

        {/* Excel Tile */}
        <div
          onClick={handleExcel}
          className="bg-white rounded-2xl border border-slate-200/80 p-3.5 shadow-2xs flex items-center gap-3.5 hover:border-emerald-400 transition-all cursor-pointer"
        >
          <div className="w-11 h-11 rounded-xl bg-emerald-50 text-emerald-600 border border-emerald-200/70 flex items-center justify-center shrink-0">
            <FileSpreadsheet className="w-5 h-5 stroke-[2.2]" />
          </div>
          <div>
            <div className="text-xs font-bold text-slate-900">Download Excel</div>
            <div className="text-[10px] text-slate-500 font-medium mt-0.5">
              Editable 5-sheet workbook with embedded formulas
            </div>
          </div>
        </div>

        {/* CSV Tile */}
        <div
          onClick={handleCsv}
          className="bg-white rounded-2xl border border-slate-200/80 p-3.5 shadow-2xs flex items-center gap-3.5 hover:border-blue-400 transition-all cursor-pointer"
        >
          <div className="w-11 h-11 rounded-xl bg-blue-50 text-blue-600 border border-blue-200/70 flex items-center justify-center shrink-0">
            <FileCode className="w-5 h-5 stroke-[2.2]" />
          </div>
          <div>
            <div className="text-xs font-bold text-slate-900">Download CSV</div>
            <div className="text-[10px] text-slate-500 font-medium mt-0.5">
              Raw comma-separated table for data analysis
            </div>
          </div>
        </div>

        {/* Print Tile */}
        <div
          onClick={handlePrint}
          className="bg-white rounded-2xl border border-slate-200/80 p-3.5 shadow-2xs flex items-center gap-3.5 hover:border-indigo-400 transition-all cursor-pointer"
        >
          <div className="w-11 h-11 rounded-xl bg-indigo-50 text-indigo-600 border border-indigo-200/70 flex items-center justify-center shrink-0">
            <Printer className="w-5 h-5 stroke-[2.2]" />
          </div>
          <div>
            <div className="text-xs font-bold text-slate-900">Print Report</div>
            <div className="text-[10px] text-slate-500 font-medium mt-0.5">
              Direct print with official supervisor formatting
            </div>
          </div>
        </div>

        {/* Share Tile */}
        <div
          onClick={handleShare}
          className="bg-white rounded-2xl border border-slate-200/80 p-3.5 shadow-2xs flex items-center gap-3.5 hover:border-emerald-400 transition-all cursor-pointer"
        >
          <div className="w-11 h-11 rounded-xl bg-emerald-50 text-emerald-700 border border-emerald-300/80 flex items-center justify-center shrink-0">
            <Share2 className="w-5 h-5 stroke-[2.2]" />
          </div>
          <div>
            <div className="text-xs font-bold text-slate-900">Share Report</div>
            <div className="text-[10px] text-slate-500 font-medium mt-0.5">
              Share via WhatsApp, Email, or Messaging
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
